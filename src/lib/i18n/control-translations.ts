const controlSelector = "button, a, summary, label, input, textarea, select, [role='button'], [role='option'], [role='tab'], [role='menuitem']";

function translateTextNodes(root: Node) {
  const nodes: Text[] = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let walked: Node | null;
  while ((walked = walker.nextNode())) nodes.push(walked as Text);
  if (root.nodeType === Node.TEXT_NODE) nodes.push(root as Text);
  if (root instanceof Element || root instanceof Document) {
    root.querySelectorAll("*").forEach((element) => {
      if (element.children.length === 0 && element.firstChild?.nodeType === Node.TEXT_NODE) {
        nodes.push(element.firstChild as Text);
      }
    });
  }
  for (const textNode of nodes) {
    const source = textNode.nodeValue?.trim();
    if (!source) continue;
    // Message-key screens are translated here as a compatibility bridge while
    // legacy screens are migrated. Exact matching keeps user-entered content
    // (job titles, notes, and review text) untouched.
    const messageTranslation = Object.values(messages).find((entry) => entry["zh-TW"] === source)?.en;
    let translation = messageTranslation ?? englishControlTranslations[source];
    if (!translation) {
      const nextSyncMatch = source.match(/^下次：\s*(不會自動同步|.+)$/);
      if (nextSyncMatch) translation = `Next: ${nextSyncMatch[1] === "不會自動同步" ? "No automatic sync" : nextSyncMatch[1]}`;
      const appliedMatch = source.match(/^修改／已投\s+(\d+)$/);
      if (appliedMatch) translation = `Editing / Applied ${appliedMatch[1]}`;
      const resumeCountMatch = source.match(/^(\d+) 份履歷$/);
      if (resumeCountMatch) translation = `${resumeCountMatch[1]} resume${resumeCountMatch[1] === "1" ? "" : "s"}`;
      const linkedinSourceMatch = source.match(/^從「(.+)」生成優化的 LinkedIn 內容$/);
      if (linkedinSourceMatch) translation = `Generate optimized LinkedIn content from “${linkedinSourceMatch[1]}”`;
      const characterCountMatch = source.match(/^(\d+) 字$/);
      if (characterCountMatch) translation = `${characterCountMatch[1]} characters`;
    }
    if (!translation) {
      const countMatch = source.match(/^(全部|已收藏|面試|收藏)\s*\((\d+)\)$/);
      if (countMatch) {
        const label = { "全部": "All", "已收藏": "Bookmarked", "面試": "Interview", "收藏": "Bookmarked" }[countMatch[1]];
        translation = `${label} (${countMatch[2]})`;
      }
      const scoreMatch = source.match(/^ATS 分數$/);
      if (scoreMatch) translation = "ATS score";
    }
    if (translation) textNode.nodeValue = textNode.nodeValue!.replace(source, translation);
  }
}

export function translateEnglishControls(root: ParentNode = document) {
  // Walk the full rendered tree: headings and descriptions were historically
  // outside the control selector and were the main source of mixed-language UI.
  translateTextNodes(root as Node);
  root.querySelectorAll(controlSelector).forEach((element) => {
    const elementText = element.textContent?.trim();
    const elementTranslation = elementText
      ? englishControlTranslations[elementText] ?? elementText.replace(/^(全部|已收藏|面試|收藏)\s*\((\d+)\)$/, (_match, label: string, count: string) => `${({ "全部": "All", "已收藏": "Bookmarked", "面試": "Interview", "收藏": "Bookmarked" } as Record<string, string>)[label]} (${count})`)
      : undefined;
    if (elementTranslation && elementTranslation !== elementText && element.children.length === 0) {
      element.textContent = elementTranslation;
    }
    for (const attribute of ["aria-label", "title", "placeholder"]) {
      const value = element.getAttribute(attribute);
      const translation = value
        ? Object.values(messages).find((entry) => entry["zh-TW"] === value)?.en ?? englishControlTranslations[value]
        : undefined;
      if (translation) element.setAttribute(attribute, translation);
    }
  });
}
